def test_read_git_commits_preserves_multiline_messages_and_emails(git_repo: Path) -> None:
    base = _git(git_repo, "rev-parse", "HEAD")
    _git(git_repo, "commit", "-q", "--allow-empty", "-m", "feat: one\n\nBody\nline")
    _git(git_repo, "commit", "-q", "--allow-empty", "-m", "fix: two", email="dev@example.com")

    commits = read_git_commits([f"{base}..HEAD"], cwd=git_repo)

    assert [commit.message.strip() for commit in commits] == ["fix: two", "feat: one\n\nBody\nline"]
    assert [commit.author_email for commit in commits] == ["dev@example.com", _CLEAN_EMAIL]


def test_scan_push_reports_ref_message_and_email_findings(git_repo: Path) -> None:
    base = _git(git_repo, "rev-parse", "HEAD")
    _git(git_repo, "commit", "-q", "--allow-empty", "-m", MSG_DENY[3], email=EMAIL_DENY[0])
    head = _git(git_repo, "rev-parse", "HEAD")

    findings = scan_push(
        PushTarget(remote_ref=f"refs/heads/{REF_DENY[1]}", rev_args=(f"{base}..{head}",)),
        cwd=git_repo,
    )

    assert [finding.rule for finding in findings] == ["ref-name", "commit-message", "email"]


def test_cli_commit_msg_exit_codes(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    clean = tmp_path / "clean"
    clean.write_text(MSG_ALLOW[2] + "\n", encoding="utf-8")
    dirty = tmp_path / "dirty"
    dirty.write_text(MSG_DENY[0], encoding="utf-8")

    assert attribution_guard.main(["commit-msg", str(clean)]) == 0
    assert attribution_guard.main(["commit-msg", str(dirty)]) == 1
    assert "commit message: matched commit-message pattern" in capsys.readouterr().err


def test_cli_push_audits_pushed_range(git_repo: Path) -> None:
    before = _git(git_repo, "rev-parse", "HEAD")
    _git(git_repo, "commit", "-q", "--allow-empty", "-m", "fix: clean")
    clean_after = _git(git_repo, "rev-parse", "HEAD")
    _git(git_repo, "commit", "-q", "--allow-empty", "-m", MSG_DENY[6])
    dirty_after = _git(git_repo, "rev-parse", "HEAD")
    common = ["push", "--ref", "refs/heads/main", "--repo-root", str(git_repo)]

    assert attribution_guard.main([*common, "--before", before, "--after", clean_after]) == 0
    assert attribution_guard.main([*common, "--before", before, "--after", dirty_after]) == 1


