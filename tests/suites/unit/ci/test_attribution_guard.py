def _git(repo: Path, *args: str, email: str = _CLEAN_EMAIL) -> str:
    # Isolate from user config such as commit signing or hooks.
    environ = {
        **os.environ,
        "GIT_AUTHOR_NAME": "Maintainer",
        "GIT_AUTHOR_EMAIL": email,
        "GIT_COMMITTER_NAME": "Maintainer",
        "GIT_COMMITTER_EMAIL": _CLEAN_EMAIL,
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_NOSYSTEM": "1",
    }
    result = subprocess.run(
        ["git", *args], cwd=repo, env=environ, check=True, capture_output=True, text=True
    )
    return result.stdout.strip()


