def _patch_pull_request_api(
    test_context: TestContext,
    *,
    pull: dict[str, object],
    commits: list[dict[str, object]],
) -> list[str]:
    requested: list[str] = []

    def fake_get_object(*, url: str, token: str) -> dict[str, object]:
        assert token == "token"
        requested.append(url)
        return pull

    def fake_paginated_get(*, url: str, token: str) -> list[dict[str, object]]:
        assert token == "token"
        requested.append(url)
        return commits

    test_context.patch.patch_object(attribution, "github_get_object", new=fake_get_object)
    test_context.patch.patch_object(attribution, "github_paginated_get", new=fake_paginated_get)
    return requested


def _pull_payload(**overrides: object) -> dict[str, object]:
    payload: dict[str, object] = {
        "title": "ci: add guard",
        "body": None,
        "head": {"ref": "ci/add-guard"},
        "labels": [{"name": "dependencies"}],
        "commits": 2,
    }
    payload.update(overrides)
    return payload


def test_fetch_pull_request_snapshot_refetches_metadata_and_every_commit(
    test_context: TestContext,
) -> None:
    requested = _patch_pull_request_api(
        test_context,
        pull=_pull_payload(),
        commits=[_api_commit("1" * 40, "ci: one"), _api_commit("2" * 40, "ci: two")],
    )

    snapshot = fetch_pull_request_snapshot(
        repository="jsugg/strongclaw",
        number=9,
        token="token",
        api_base="https://api.example.test/",
    )

    assert requested == [
        "https://api.example.test/repos/jsugg/strongclaw/pulls/9",
        "https://api.example.test/repos/jsugg/strongclaw/pulls/9/commits?per_page=100",
    ]
    assert snapshot.body == ""
    assert snapshot.head_ref == "ci/add-guard"
    assert snapshot.labels == ("dependencies",)
    assert [commit.committer_email for commit in snapshot.commits] == [
        "noreply@github.com",
        "noreply@github.com",
    ]


